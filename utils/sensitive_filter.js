/**
 * 校验文本是否含有违规敏感词
 * @param {string} text - 需要检测的文本
 * @returns {{ pass: boolean, word?: string, reason?: string }}
 */
function checkTextSecurity(text) {
  if (!text || typeof text !== 'string') {
    return { pass: true };
  }

  // 去除空格和特殊无意义符号后统一检测，防止空格或标点穿插绕过（例如 "加 v x"、"操*你*妈"）
  const normalized = text.toLowerCase().replace(/[\s\r\n\t~`!@#$%^&*()_\-+={}[\]|\\:;"'<>,.?/·！￥…（）—【】、；：‘’“”《》，。？]/g, '');

  for (const word of SENSITIVE_WORDS) {
    const cleanWord = word.toLowerCase().replace(/[\s]/g, '');
    if (normalized.includes(cleanWord) || text.toLowerCase().includes(word.toLowerCase())) {
      return {
        pass: false,
        word: word,
        reason: '内容包含违规字词，请文明用语！'
      };
    }
  }

  return { pass: true };
}

